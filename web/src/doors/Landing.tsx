// The landing page (SPEC 7, doors/): where a plain visit opens (?door=home; the header's brand
// comes back to it). The promise and one primary button, door 1's story; then the three doors in a
// few lines each, the explanatory copy the live screen used to carry under the picture, every
// feature a link that opens it as its deep link does (a real href, so it can be copied or opened in
// a new tab; a plain click opens it in place); then the evidence in one line and the demo-data
// note. Nothing here plays or asks the service for anything: the picture waits behind The look.

import type { MouseEvent, ReactNode } from "react";
import { drillOf } from "../drill/controller";
import { JOURNEY_STEPS, STEP_MARK, STEP_TITLE, type JourneyStep } from "../journey/steps";
import { openStep } from "../journey/state";
import { DemoBadge } from "../journey/DemoBadge";
import { SourceChip } from "../provenance/SourceChip";
import { useSession } from "../session";
import { stepThroughOf } from "../steps/controller";
import { useStore } from "../store/store";
import { takeEyesOf } from "../takeeyes/controller";
import { envOf, quickTourFits } from "../tour/steps";
import { startTour } from "../tour/tourState";
import { ArrowIcon, CheckIcon } from "../ui/icons";
import { hookOf, PITCH } from "../ui/IntroCard";
import { extraLooksOf } from "../without/extra";
import { useHeroGate } from "../without/WithoutLook";
import { yourCallOf } from "../yourcall/controller";
import { useReveal } from "../ui/reveal";
import { DOOR_LABEL, DOORS, type Door } from "./doors";
import { openDoor, revealCompare } from "./state";

/** The landing page's links, as addresses: what each opens, for a copy or a new tab. */
export const HOME_LINKS = {
  story: "?tour=quick",
  steps: "?play=steps",
  extra: "?compare=extra",
  yourCall: "?play=yourcall",
  eyes: "?play=eyes",
  drill: "?play=drill",
  step: (step: JourneyStep) => `?door=studios&step=${step}`,
} as const;

const href = (search: string) => `${import.meta.env.BASE_URL}${search}`;

/** Door 1's story from the top: the quick tour where the moment has one, else the breakdown. */
function useWatch(): { label: string; title?: string; watch: () => void } {
  const session = useSession();
  const story = quickTourFits(envOf(session));
  return {
    label: story ? "Watch the look (60 s)" : "Watch it through his eyes",
    title: story ? "His look, the run without it, the two compared: about a minute" : undefined,
    watch: () => {
      openDoor("look", { address: true });
      window.scrollTo({ top: 0 });
      if (story) startTour(null, "quick");
      else session.controls.playBreakdown();
    },
  };
}

export function Landing() {
  const session = useSession();
  const { line } = hookOf(session);
  const { label, title, watch } = useWatch();
  const cut = line.lastIndexOf(" ");
  return (
    <section className="door-page door-home" aria-labelledby="home-title">
      <header className="door-head home-head">
        <p className="kicker accent">One moment · through his eyes</p>
        <h2 id="home-title" tabIndex={-1}>
          {line.slice(0, cut)} <em>{line.slice(cut + 1)}</em>
        </h2>
        <p className="lede">{PITCH}</p>
        <div className="home-cta">
          <button type="button" className="btn btn-primary" title={title} onClick={watch}>
            {label}
            <ArrowIcon />
          </button>
        </div>
      </header>
      <div className="home-doors">
        <LookDoor />
        <TurnDoor />
        <StudiosDoor />
      </div>
      <Evidence />
      <p className="note home-demo">
        All players and clubs are fictional; the match is generated by our simulator.{" "}
        <DemoBadge compact />
      </p>
    </section>
  );
}

/** One door: its name, two or three lines, and its features as links. */
function DoorSection({
  door,
  children,
  links,
}: {
  door: Door;
  children: ReactNode;
  links: { key: string; href: string; label: string; open: () => void }[];
}) {
  const id = `home-door-${door}`;
  const reveal = useReveal<HTMLElement>(DOORS.indexOf(door));
  return (
    <section className={`home-door home-door-${door}`} aria-labelledby={id} ref={reveal}>
      <h3 id={id}>{DOOR_LABEL[door]}</h3>
      <p className="home-door-line">{children}</p>
      <ul className="home-links" aria-label={`${DOOR_LABEL[door]}: features`}>
        {links.map((l) => (
          <li key={l.key}>
            <a
              className="home-link"
              href={href(l.href)}
              onClick={(e: MouseEvent<HTMLAnchorElement>) => {
                // A modified click opens the address in a new tab, as any link does.
                if (e.metaKey || e.ctrlKey || e.shiftKey || e.altKey || e.button !== 0) return;
                e.preventDefault();
                l.open();
              }}
            >
              {l.label}
              <ArrowIcon />
            </a>
          </li>
        ))}
      </ul>
    </section>
  );
}

/** Door 1: the story, his looks one by one, the run with two more looks. */
function LookDoor() {
  const session = useSession();
  const { watch } = useWatch();
  const steps = stepThroughOf(session);
  const extra = extraLooksOf(session);
  const hasExtra = useStore(extra.state, (s) => s.data !== null);
  const story = quickTourFits(envOf(session));
  const links = [
    ...(story ? [{ key: "story", href: HOME_LINKS.story, label: "The story", open: watch }] : []),
    ...(steps.unavailable
      ? []
      : [
          {
            key: "steps",
            href: HOME_LINKS.steps,
            label: "Step through his looks",
            open: () => {
              openDoor("look", { address: true });
              window.scrollTo({ top: 0 });
              steps.open();
            },
          },
        ]),
    ...(hasExtra
      ? [
          {
            key: "extra",
            href: HOME_LINKS.extra,
            label: "With two more looks",
            open: () => {
              extra.compare.set({ value: "extra" });
              openDoor("look", { address: true });
              revealCompare();
            },
          },
        ]
      : []),
  ];
  return (
    <DoorSection door="look" links={links}>
      He decides on what he believes, never on the truth. Watch his look, then the same seconds
      re-simulated without it: only this look changes; the match and seed stay the same.
    </DoorSection>
  );
}

/** Door 2: the modes where the viewer is the player, each opening over Your turn's hub. */
function TurnDoor() {
  const session = useSession();
  const modes = [
    { key: "yourCall", label: "Make his call", c: yourCallOf(session), href: HOME_LINKS.yourCall },
    { key: "eyes", label: "See through his eyes", c: takeEyesOf(session), href: HOME_LINKS.eyes },
    { key: "drill", label: "Train your scanning", c: drillOf(session), href: HOME_LINKS.drill },
  ];
  const links = modes
    .filter((m) => !m.c.unavailable)
    .map((m) => ({
      key: m.key,
      href: m.href,
      label: m.label,
      open: () => {
        openDoor("turn", { address: true });
        window.scrollTo({ top: 0 });
        m.c.open();
      },
    }));
  return (
    <DoorSection door="turn" links={links}>
      You are the player; see what he could see. Decide with only what he knew, choose when and
      where he looks, or check your shoulder before the ball arrives.
    </DoorSection>
  );
}

/** Door 3: the four solutions and their value, each opening its section. */
function StudiosDoor() {
  const links = JOURNEY_STEPS.map((step) => ({
    key: step,
    href: HOME_LINKS.step(step),
    label: STEP_MARK[step]
      ? `${STEP_MARK[step]} · ${STEP_TITLE[step].replace(/^AI /, "")}`
      : "Value",
    open: () => {
      openDoor("studios", { address: true });
      openStep(step, { address: true });
    },
  }));
  return (
    <DoorSection door="studios" links={links}>
      What one moment does for the league: four solutions, broadcast and social first, then what
      they are worth. Every panel builds on the verified breakdown.
    </DoorSection>
  );
}

/** The evidence, in one line: how often the look changes the outcome over held-out seeds (read
 * from hero_gates.json, never typed here), and the Verifier. */
function Evidence() {
  const gate = useHeroGate();
  return (
    <p className="home-evidence">
      {gate && (
        <span className="home-gate">
          <b>
            {gate.changed}/{gate.n}
          </b>{" "}
          held-out seeds: without the look he{" "}
          {gate.what === "decision" ? "decides" : "places the shot"} differently.{" "}
          <SourceChip kind="sim" title={`Eval result from ${gate.report}`} spoken />
        </span>
      )}
      <span className="home-verifier">
        <CheckIcon size={12} /> Every number the commentary says is checked in code by the Verifier;
        a wrong one never airs.
      </span>
    </p>
  );
}
