// Page layout: header with the run toggle, the two views, transport, then the panels.

import { useEffect } from "react";
import { startClock, useSession } from "./session";
import { useStore } from "./store/store";
import { BreakdownPanel } from "./ui/BreakdownPanel";
import { EvidenceCard, NarrationPanel } from "./ui/Narration";
import { DecisionPanel, StoryPanel } from "./ui/Panels";
import { Transport } from "./ui/Transport";
import { PovView } from "./views/PovView";
import { TacticalView } from "./views/TacticalView";

export function App({ autoplay }: { autoplay: boolean }) {
  const session = useSession();
  const { playback, controls } = session;
  const mode = useStore(playback, (s) => s.mode);
  const focus = useStore(playback, (s) => s.focus);

  useEffect(() => startClock(session), [session]);
  useEffect(() => {
    if (autoplay) controls.playBreakdown();
  }, [autoplay, controls]);

  return (
    <div className={mode === "counterfactual" ? "app mode-cf" : "app"}>
      <header>
        <div className="brand">
          <h1>
            Through Their Eyes <span className="tag">synthetic match</span>
          </h1>
          <p>
            Hero moment: the blind-side run. See what the midfielder saw, and what he would have
            done without one look over his shoulder.
          </p>
        </div>
        <div className="segmented" role="group" aria-label="Run">
          <button
            type="button"
            aria-pressed={mode === "factual"}
            onClick={() => controls.setMode("factual")}
          >
            With the look
          </button>
          <button
            type="button"
            className="cf"
            aria-pressed={mode === "counterfactual"}
            onClick={() => controls.setMode("counterfactual")}
          >
            Without the look
          </button>
        </div>
      </header>

      <section className={`stage focus-${focus}`}>
        <PovView />
        <TacticalView />
      </section>

      <EvidenceCard />

      <Transport />

      <section className="below">
        <NarrationPanel />
        <BreakdownPanel />
        <StoryPanel />
        <DecisionPanel />
      </section>

      <footer className="legend">
        <span>
          <i style={{ background: "var(--home)" }} />
          Home (attacking right)
        </span>
        <span>
          <i style={{ background: "var(--away)" }} />
          Away
        </span>
        <span>
          <i style={{ background: "var(--sight)" }} />
          In his sight right now
        </span>
        <span>
          <i className="dashed" />
          Where he believes a player is
        </span>
        <span>All players and clubs are fictional; the match is generated by our simulator.</span>
      </footer>
    </div>
  );
}
